const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Module = require('node:module');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'notus-direct-image-'));
Object.assign(process.env, { NOTUS_RUNTIME_TARGET: 'web', NOTUS_DATA_ROOT: root, NOTES_DIR: path.join(root, 'notes'), ASSETS_DIR: path.join(root, 'assets'), DB_PATH: path.join(root, 'db.sqlite'), LOG_DIR: path.join(root, 'logs') });
const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
const configFile = require.resolve('../lib/llmConfigs');
require.cache[configFile] = { id: configFile, filename: configFile, loaded: true, exports: { resolveLlmRuntimeConfig: () => ({ llmContextWindowTokens: 60000 }) } };
(async () => {
  const { getDb } = require('../lib/db');
  const { ensureConversation, appendConversationMessage } = require('../lib/conversations');
  const { getImagesDir, makeConversationImageReference } = require('../lib/conversationImages');
  const { createSession, getSession, loadMessagesCheckpoint } = require('../lib/agentSession');
  const { createTask, getTaskBySession } = require('../lib/agentTaskQueue');
  const llm = require('../lib/llm');
  const cid = ensureConversation({ kind: 'agent', title: '直接看图' }).id;
  fs.mkdirSync(getImagesDir(), { recursive: true });
  const img = { id: 'direct', name: 'image.png', stored_name: 'direct.png', extension: '.png', upload_order: 0 };
  fs.writeFileSync(path.join(getImagesDir(), img.stored_name), Buffer.from(png, 'base64'));
  const mid = appendConversationMessage({ conversationId: cid, role: 'user', content: '描述图中可见内容', meta: { images: [img] } });
  const sid = createSession({ goal: '描述图中可见内容', conversationId: cid, mcpSelection: { mode: 'off' } }).sessionId;
  const task = createTask({ sessionId: sid, conversationId: cid, userMessageId: mid, input: { user_query: '描述图中可见内容', images: [img] } });
  let calls = 0;
  let expectingImage = true;
  llm.completeToolChat = async request => {
    calls++;
    assert.equal(request.taskType, 'agent_loop', '不允许独立视觉模型调用');
    const blocks = request.messages.flatMap(m => Array.isArray(m.content) ? m.content : []);
    if (!expectingImage) {
      assert(!blocks.some(b => b.type === 'image'));
      return { content: [{ type: 'text', text: '幂等表示重复执行同一操作，结果与执行一次相同。' }], stopReason: 'end_turn' };
    }
    assert.equal(blocks.filter(b => b.type === 'image').length, 1);
    assert.equal(blocks.find(b => b.type === 'image').source.data, png);
    assert(llm.toAnthropicMessages(request.messages).some(m => m.content.some(b => b.type === 'image')));
    assert(llm.toOpenAiMessages('', request.messages).some(m => Array.isArray(m.content) && m.content.some(b => b.type === 'image_url')));
    const checkpoint = JSON.stringify(loadMessagesCheckpoint(sid));
    assert(!checkpoint.includes(png)); assert(checkpoint.includes('image_reference'));
    return { content: [{ type: 'text', text: '图片是一张很小的图像，没有可辨认的文字。' }], stopReason: 'end_turn' };
  };
  delete require.cache[require.resolve('../lib/agentLoop')];
  const filename = require.resolve('../lib/agentTaskWorker'); const mod = new Module(filename, module); mod.filename = filename; mod.paths = Module._nodeModulePaths(path.dirname(filename));
  mod._compile(fs.readFileSync(filename, 'utf8') + '\nmodule.exports.executeForTest=execute;', filename);
  await mod.exports.executeForTest(task);
  assert.equal(calls, 1); assert.equal(getTaskBySession(sid).status, 'completed', JSON.stringify(getTaskBySession(sid).last_error));
  assert.equal(getDb().prepare("SELECT count(*) n FROM messages WHERE conversation_id=? AND type='parsed_attachment'").get(cid).n, 0);
  const { projectImageMessages } = require('../lib/agentImageContext');
  const reference = [{ role: 'user', content: [{ type: 'image_reference', image_ref: makeConversationImageReference(mid, img.id) }] }];
  const restored = await projectImageMessages(reference, getSession(sid));
  assert(restored[0].content.some(b => b.type === 'image'), '恢复时通过引用重新加载原图');
  const otherId = ensureConversation({ kind: 'agent', title: '隔离会话' }).id;
  const otherSession = createSession({ goal: '看图', conversationId: otherId }).sessionId;
  const denied = await projectImageMessages(reference, getSession(otherSession));
  assert(!denied[0].content.some(b => b.type === 'image')); assert(JSON.stringify(denied).includes('CONVERSATION_IMAGE_NOT_FOUND'));
  const cancel = new AbortController(); cancel.abort();
  await assert.rejects(projectImageMessages(reference, getSession(sid), { signal: cancel.signal }), /abort/i);
  expectingImage = false; calls = 0;
  const simpleId = createSession({ goal: '解释幂等这个术语', conversationId: cid, mcpSelection: { mode: 'off' } }).sessionId;
  await mod.exports.executeForTest(createTask({ sessionId: simpleId, conversationId: cid, input: { user_query: '解释幂等这个术语' } }));
  assert.equal(calls, 1, '术语解释仍走同一 Loop，只需一次主模型请求');
  assert.equal(getTaskBySession(simpleId).status, 'completed');
  mod.exports.stopAgentTaskWorker(); require('../lib/skills').stopSkillWatchers(); getDb().close(); fs.rmSync(root, { recursive: true, force: true });
  console.log('direct image: one Agent request, both protocols, reference checkpoint, restoration, isolation and cancellation passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
